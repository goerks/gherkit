package scaffold

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
	"text/template"
)

// CIOptions describes the pipeline `gherkit ci` generates.
type CIOptions struct {
	Provider string // github, gitlab or azure
	Version  string // gherkit release to install, without "v"; "latest" resolves it in the pipeline
	Features string // folder checked by fmt and lint
	Adapter  string // runner adapter; empty: the pipeline does not run tests
	Report   string // path of the HTML report
}

type provider struct {
	path string // default file
	tmpl string
}

// Delimiters [[ ]] keep the templates free of clashes with ${{ }} of GitHub Actions.
var providers = map[string]provider{
	"github": {".github/workflows/gherkit.yml", githubTmpl},
	"gitlab": {".gitlab-ci.yml", gitlabTmpl},
	"azure":  {"azure-pipelines.yml", azureTmpl},
}

// Providers lists the supported CI systems.
func Providers() []string {
	var n []string
	for k := range providers {
		n = append(n, k)
	}
	sort.Strings(n)
	return n
}

// DefaultCIPath is where the pipeline of a provider conventionally lives.
func DefaultCIPath(name string) (string, bool) {
	p, ok := providers[name]
	return p.path, ok
}

const installSh = `V="[[.Version]]"
if [ "$V" = latest ]; then V=$(curl -fsSL https://api.github.com/repos/goerks/gherkit/releases/latest | sed -n 's/.*"tag_name": *"v\{0,1\}\([^"]*\)".*/\1/p'); fi
test -n "$V" || { echo "cannot find the latest gherkit release" >&2; exit 1; }
mkdir -p "$HOME/.local/bin"
curl -fsSL "https://github.com/goerks/gherkit/releases/download/v${V}/gherkit_${V}_linux_amd64.tar.gz" | tar -xz -C "$HOME/.local/bin" gherkit
`

// CI renders the pipeline of a provider.
func CI(o CIOptions) (File, error) {
	p, ok := providers[o.Provider]
	if !ok {
		return File{}, fmt.Errorf("unknown CI provider %q (available: %s)", o.Provider, strings.Join(Providers(), ", "))
	}
	if o.Version == "" {
		o.Version = "latest"
	}
	if strings.ContainsAny(o.Version, " \"'$`\\\n") || strings.ContainsAny(o.Features+o.Adapter+o.Report, " \"'$`\\\n") {
		return File{}, fmt.Errorf("version, features folder, adapter and report path must not contain spaces or quotes")
	}
	if o.Features == "" {
		o.Features = "."
	}
	if o.Report == "" {
		o.Report = "build/gherkit-report.html"
	}
	if o.Adapter != "" && o.Adapter != "go" && o.Adapter != "java" {
		return File{}, fmt.Errorf("the pipeline templates know the adapters go and java, not %q", o.Adapter)
	}
	t, err := template.New(o.Provider).Delims("[[", "]]").Funcs(template.FuncMap{
		"indent": func(n int, s string) string {
			pad := strings.Repeat(" ", n)
			lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
			for i, l := range lines {
				lines[i] = pad + l
			}
			return strings.Join(lines, "\n")
		},
	}).Parse(p.tmpl)
	if err != nil {
		return File{}, err
	}
	// The install snippet is itself a template (version).
	it := template.Must(template.New("install").Delims("[[", "]]").Parse(installSh))
	var install bytes.Buffer
	if err := it.Execute(&install, o); err != nil {
		return File{}, err
	}
	var b bytes.Buffer
	if err := t.Execute(&b, struct {
		CIOptions
		Install string
	}{o, install.String()}); err != nil {
		return File{}, err
	}
	return File{Path: p.path, Content: b.String()}, nil
}

const githubTmpl = `# Generated by "gherkit ci". Checks the Gherkin files[[if .Adapter]], runs the tests[[end]] and publishes a report.
name: gherkit

on:
  push:
    branches: [main]
  pull_request:

permissions:
  contents: read

jobs:
  gherkit:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
[[- if eq .Adapter "go"]]
      - uses: actions/setup-go@v5
        with:
          go-version-file: go.mod
[[- end]]
[[- if eq .Adapter "java"]]
      - uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: "21"
[[- end]]
      - name: Install gherkit
        run: |
[[indent 10 .Install]]
          echo "$HOME/.local/bin" >> "$GITHUB_PATH"
      - name: Format
        run: gherkit fmt --check [[.Features]]
      - name: Lint
        run: gherkit lint --strict -o github [[.Features]]
[[- if .Adapter]]
      - name: Run tests
        run: gherkit run --adapter [[.Adapter]] --report [[.Report]]
[[- end]]
      - uses: actions/upload-artifact@v4
        if: always() && hashFiles('[[.Report]]') != ''
        with:
          name: gherkit-report
          path: [[.Report]]
`

const gitlabTmpl = `# Generated by "gherkit ci". Checks the Gherkin files[[if .Adapter]], runs the tests[[end]] and publishes a report.
# Already have a .gitlab-ci.yml? Write this to another file (-o) and add it with "include:".
gherkit:
[[- if eq .Adapter "go"]]
  image: golang:1.24
[[- else if eq .Adapter "java"]]
  image: maven:3-eclipse-temurin-21
[[- else]]
  image: debian:stable-slim
[[- end]]
  script:
    - command -v curl >/dev/null || (apt-get update -qq && apt-get install -y -qq curl ca-certificates)
    - |
[[indent 6 .Install]]
    - export PATH="$HOME/.local/bin:$PATH"
    - gherkit fmt --check [[.Features]]
    - gherkit lint --strict [[.Features]]
[[- if .Adapter]]
    - gherkit run --adapter [[.Adapter]] --report [[.Report]]
[[- end]]
  artifacts:
    when: always
    paths:
      - [[.Report]]
`

const azureTmpl = `# Generated by "gherkit ci". Checks the Gherkin files[[if .Adapter]], runs the tests[[end]] and publishes a report.
trigger:
  - main

pool:
  vmImage: ubuntu-latest

steps:
[[- if eq .Adapter "go"]]
  - task: GoTool@0
    inputs:
      version: "1.24"
[[- end]]
[[- if eq .Adapter "java"]]
  - task: JavaToolInstaller@0
    inputs:
      versionSpec: "21"
      jdkArchitectureOption: x64
      jdkSourceOption: PreInstalled
[[- end]]
  - script: |
[[indent 6 .Install]]
      echo "##vso[task.prependpath]$HOME/.local/bin"
    displayName: Install gherkit
  - script: gherkit fmt --check [[.Features]]
    displayName: Format
  - script: gherkit lint --strict [[.Features]]
    displayName: Lint
[[- if .Adapter]]
  - script: gherkit run --adapter [[.Adapter]] --report [[.Report]]
    displayName: Run tests
[[- end]]
  - task: PublishBuildArtifacts@1
    condition: succeededOrFailed()
    inputs:
      pathToPublish: [[.Report]]
      artifactName: gherkit-report
`
